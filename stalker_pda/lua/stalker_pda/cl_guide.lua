-- Разделы справочника, сгруппированные для каталога.
function P.GuideData()
 local groups,byName={},{}
 for _,name in ipairs(P.GuideGroups) do byName[name]={title=name,items={}};groups[#groups+1]=byName[name] end
 local list={};for _,def in pairs(P.Guide) do list[#list+1]=def end
 table.sort(list,function(a,b) if a.order~=b.order then return a.order<b.order end;return a.id<b.id end)
 for _,def in ipairs(list) do
  local g=byName[def.group]
  if not g then g={title=def.group,items={}};byName[def.group]=g;groups[#groups+1]=g end
  local blocks=def.blocks
  if type(blocks)=="function" then local ok,res=pcall(blocks);blocks=ok and type(res)=="table" and res or {} end
  g.items[#g.items+1]={id="guide."..def.id,title=def.title or def.id,subtitle=def.subtitle,blocks=type(blocks)=="table" and blocks or {}}
 end
 local out={};for _,g in ipairs(groups) do if #g.items>0 then out[#out+1]=g end end
 return out
end

P.AddTab("guide",{title="Справочник",order=70,build=function(parent)
 local state=P.Catalog(parent,P.GuideData(),{placeholder="Поиск по справочнику…",selected=P.GuideSelected})
 local select=state.select
 state.select=function(id) P.GuideSelected=id;select(id) end
end})
